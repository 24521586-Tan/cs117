# Define schemas for the LLM Judge
class CriterionScore(BaseModel):
    score: float = Field(description="Score from 1.0 to 5.0")
    explanation: str = Field(description="Detailed explanation in Vietnamese of why this score was given")

class EvalResult(BaseModel):
    summary_completeness: CriterionScore = Field(description="Recall of main discussion topics and key decisions in the summary")
    summary_accuracy: CriterionScore = Field(description="Factual accuracy of the summary, no hallucinations")
    task_completeness: CriterionScore = Field(description="Are all tasks/action items mentioned in the meeting extracted? No missing tasks")
    task_assignment_accuracy: CriterionScore = Field(description="Are tasks assigned to the correct person based on context? (e.g. Gang Chen, Students, Unassigned)")
    task_quote_accuracy: CriterionScore = Field(description="Do verbatim quotes in tasks exactly match transcript segments?")
    overall_comments: str = Field(description="Overall summary of quality and recommendations in Vietnamese")

JUDGE_SYSTEM_INSTRUCTION = (
    "You are an objective AI evaluator. Your job is to evaluate the quality of a meeting analysis "
    "generated by another AI, against the raw transcript and slide text of the meeting.\n"
    "You must rate the meeting analysis on five criteria from 1.0 to 5.0 (where 5.0 is perfect):\n"
    "1. Summary Completeness (Độ đầy đủ tóm tắt): Does the summary capture all key decisions and major topics discussed? (1.0 = missed everything, 5.0 = captured everything important).\n"
    "2. Summary Factual Accuracy (Độ chính xác tóm tắt): Does the summary contain any information/assumptions not supported by the transcript or slides? (1.0 = completely hallucinated, 5.0 = 100% accurate).\n"
    "3. Task Completeness (Độ đầy đủ giao việc): Are all action items and tasks mentioned in the transcript extracted? Did it miss or leave out any tasks for any person? (1.0 = missed all tasks, 5.0 = captured all tasks).\n"
    "4. Task Assignment Accuracy (Độ chính xác phân vai): Are tasks assigned to the correct person (e.g., matching who actually agreed or was asked to do the task)? Are there tasks assigned to the wrong people? (1.0 = all wrong, 5.0 = perfectly assigned).\n"
    "5. Task Quote Accuracy (Độ chính xác trích dẫn): Do the verbatim quotes in the tasks match the actual spoken words in the transcript? (1.0 = quotes are made up, 5.0 = quotes match perfectly).\n"
    "Provide a detailed, objective justification for each score in Vietnamese."
)

def normalize_text(text: str) -> str:
    """Normalize text for fair WER comparison (lowercase, remove punctuation, normalize unicode)."""
    text = text.lower()
    text = unicodedata.normalize('NFC', text)
    text = re.sub(r'[^\w\s]', ' ', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

def calculate_wer(reference: str, hypothesis: str) -> float:
    """Calculate Word Error Rate (WER) using Levenshtein distance on words."""
    ref_words = normalize_text(reference).split()
    hyp_words = normalize_text(hypothesis).split()
    
    if not ref_words:
        return 1.0 if hyp_words else 0.0
    
    d = [[0] * (len(hyp_words) + 1) for _ in range(len(ref_words) + 1)]
    for i in range(len(ref_words) + 1):
        d[i][0] = i
    for j in range(len(hyp_words) + 1):
        d[0][j] = j
        
    for i in range(1, len(ref_words) + 1):
        for j in range(1, len(hyp_words) + 1):
            if ref_words[i-1] == hyp_words[j-1]:
                d[i][j] = d[i-1][j-1]
            else:
                substitution = d[i-1][j-1] + 1
                insertion = d[i][j-1] + 1
                deletion = d[i-1][j] + 1
                d[i][j] = min(substitution, insertion, deletion)
                
    return d[len(ref_words)][len(hyp_words)] / len(ref_words)

def evaluate_analysis_with_llm(transcript_text: str, slides_text: str, analysis: dict) -> EvalResult:
    """Call Gemini to act as a judge and evaluate the generated meeting analysis."""
    client = genai.Client(api_key=settings.GEMINI_API_KEY)
    
    analysis_str = json.dumps(analysis, indent=2, ensure_ascii=False)
    
    prompt = (
        f"=== RAW MEETING TRANSCRIPT ===\n{transcript_text}\n\n"
        f"=== SLIDE TEXT ===\n{slides_text or '(No slides provided)'}\n\n"
        f"=== GENERATED MEETING ANALYSIS ===\n{analysis_str}\n\n"
        f"Please evaluate the GENERATED MEETING ANALYSIS against the RAW MEETING TRANSCRIPT and SLIDE TEXT."
    )
    
    response = client.models.generate_content(
        model=settings.GEMINI_MODEL,  # Reusing the model configured in backend/.env
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=JUDGE_SYSTEM_INSTRUCTION,
            response_mime_type="application/json",
            response_schema=EvalResult,
            temperature=0.1,
        ),
    )
    
    parsed = getattr(response, "parsed", None)
    if isinstance(parsed, EvalResult):
        return parsed
    return EvalResult(**json.loads(response.text))

import argparse

def main():
    ap = argparse.ArgumentParser(description="Run MeetMind evaluation.")
    ap.add_argument("--file", help="Name of specific file to test (e.g., LEC1, LEC1.mp3)")
    args = ap.parse_args()

    eval_dir = Path(__file__).resolve().parent
    audios_dir = eval_dir / "audios"
    slides_dir = eval_dir / "slides"
    gt_dir = eval_dir / "transcripts_ground_truth"
    
    print("=" * 60)
    print("MEETMIND PIPELINE EVALUATION SYSTEM")
    print("=" * 60)
    print(f"Audio directory: {audios_dir}")
    print(f"Slides directory: {slides_dir}")
    print(f"Ground truth directory: {gt_dir}")
    print("-" * 60)
    
    # Scan for audios
    if args.file:
        file_query = args.file
        # Check if it has extension, otherwise try matching stems
        if not file_query.endswith((".mp3", ".wav", ".m4a")):
            audio_files = sorted(list(audios_dir.glob(f"{file_query}.*")))
        else:
            audio_files = [audios_dir / file_query]
    else:
        audio_files = []
        for ext in ("*.mp3", "*.wav", "*.m4a"):
            audio_files.extend(audios_dir.glob(ext))
        audio_files = sorted(audio_files)
    if not audio_files:
        print("❌ No audio files found in test_data/audios!")
        return
        
    results = []
    
    print(f"Found {len(audio_files)} test cases. Starting evaluation...")
    
    for audio_path in audio_files:
        name = audio_path.stem
        print(f"\n▶️ Processing: {name}")
        
        pdf_path = slides_dir / f"{name}.pdf"
        gt_path = gt_dir / f"{name}.txt"
        
        metrics = {
            "name": name,
            "has_slides": pdf_path.is_file(),
            "has_gt": gt_path.is_file(),
            "transcribe_time": 0.0,
            "duration": 0.0,
            "rtf": 0.0,
            "wer": None,
            "extract_time": 0.0,
            "analyze_time": 0.0,
            "judge_scores": None,
            "error": None
        }
        
        try:
            # 1. Speech-to-Text Transcription
            print("  [1/4] Running Transcribe...")
            t0 = time.time()
            model = _get_model()
            segments_gen, info = model.transcribe(str(audio_path), beam_size=5, vad_filter=True)
            
            segments = []
            for s in segments_gen:
                segments.append({"start": round(s.start, 2), "end": round(s.end, 2), "text": s.text.strip()})
                
            transcript = {"segments": segments, "language": info.language}
            t_transcribe = time.time() - t0
            
            metrics["transcribe_time"] = t_transcribe
            metrics["duration"] = info.duration
            metrics["rtf"] = t_transcribe / max(0.1, info.duration)
            
            raw_transcript_text = "\n".join(s["text"] for s in segments)
            print(f"        ASR Duration: {t_transcribe:.2f}s | Audio Duration: {info.duration:.2f}s | RTF: {metrics['rtf']:.3f}")
            
            # Compute WER if ground truth exists
            if metrics["has_gt"]:
                gt_text = gt_path.read_text(encoding="utf-8")
                wer = calculate_wer(gt_text, raw_transcript_text)
                metrics["wer"] = wer
                print(f"        Word Error Rate (WER): {wer*100:.2f}%")
            else:
                print("        Word Error Rate (WER): skipped (No Ground Truth text)")
                
            # 2. Slide Extraction
            slides_prompt = ""
            if metrics["has_slides"]:
                print("  [2/4] Extracting Slide Text...")
                t0 = time.time()
                slides_data = extract_slides(pdf_path.read_bytes())
                slides_prompt = pages_as_prompt(slides_data["pages"])
                t_extract = time.time() - t0
                metrics["extract_time"] = t_extract
                print(f"        Slide Extract Time: {t_extract:.2f}s | Pages: {slides_data['page_count']}")
            else:
                print("  [2/4] Slide Extraction: skipped (No Slide PDF)")
                
            # 3. Meeting Analysis (Gemini)
            print("  [3/4] Running Gemini Analysis...")
            t0 = time.time()
            analysis = analyze_meeting(transcript, slides_prompt)
            t_analyze = time.time() - t0
            metrics["analyze_time"] = t_analyze
            print(f"        Analysis Time: {t_analyze:.2f}s")
            
            # 4. LLM-as-a-Judge Evaluation
            print("  [4/4] LLM Judge Scoring (Detailed criteria)...")
            judge_res = evaluate_analysis_with_llm(raw_transcript_text, slides_prompt, analysis)
            metrics["judge_scores"] = judge_res.model_dump()
            
            # Calculate combined scores (scaled to 1.0)
            sc = judge_res.summary_completeness.score
            sa = judge_res.summary_accuracy.score
            tc = judge_res.task_completeness.score
            ta = judge_res.task_assignment_accuracy.score
            tq = judge_res.task_quote_accuracy.score
            
            summary_score = (sc + sa) / 10.0
            task_score = (tc + ta + tq) / 15.0
            
            print(f"        Scores: S-Comp={sc} | S-Acc={sa} | T-Comp={tc} | T-Assign={ta} | T-Quote={tq}")
            print(f"        Aggregated: Summary Score = {summary_score:.2f}/1.00 | Task Score = {task_score:.2f}/1.00")
            
        except Exception as e:
            print(f"  ❌ Error processing {name}: {str(e)}")
            metrics["error"] = str(e)
            
        results.append(metrics)
        
        # Ghi đè báo cáo liên tục sau mỗi file để cập nhật tiến độ ngay lập tức
        write_report(results, eval_dir / "evaluation_report.md")
        print(f"  📝 Updated report at evaluation/evaluation_report.md")
        
    print("\n" + "=" * 60)
    print("EVALUATION COMPLETED SUCCESSFULLY!")
    print(f"Final report written to: {eval_dir / 'evaluation_report.md'}")
    print("=" * 60)
 
def write_report(results: list, report_path: Path):
    """Generate a clean markdown report summarizing all the metrics."""
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("# Báo Cáo Đánh Giá Hiệu Năng Dự Án MeetMind\n\n")
        f.write(f"Ngày đánh giá: {time.strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write(f"Số lượng mẫu thử: {len(results)} bài test\n\n")
        
        # Section 1: Summary Table
        f.write("## 1. Bảng Tổng Hợp Số Liệu (Summary Metrics)\n\n")
        f.write("| Bài Test | Thời lượng Audio | RTF | WER (%) | Điểm Tóm tắt (1.0) | Tóm tắt (Đầy đủ/Chính xác) | Điểm Giao việc (1.0) | Giao việc (Đầy đủ/Đúng/Trích) | Trạng thái |\n")
        f.write("| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |\n")
        
        total_duration = 0.0
        total_transcribe_time = 0.0
        wer_sum = 0.0
        wer_count = 0
        
        s_comp_scores = []
        s_acc_scores = []
        t_comp_scores = []
        t_assign_scores = []
        t_quote_scores = []
        successful_runs = 0
        
        for r in results:
            name = r["name"]
            duration_str = f"{r['duration']/60:.2f} phút" if r["duration"] > 0 else "-"
            rtf_str = f"{r['rtf']:.3f}" if r["rtf"] > 0 else "-"
            
            wer_str = "-"
            if r["wer"] is not None:
                wer_str = f"{r['wer']*100:.1f}%"
                wer_sum += r["wer"]
                wer_count += 1
                
            if r["error"]:
                f.write(f"| {name} | - | - | - | - | - | - | - | ❌ Lỗi ({r['error'][:30]}) |\n")
            else:
                successful_runs += 1
                total_duration += r["duration"]
                total_transcribe_time += r["transcribe_time"]
                
                scores = r["judge_scores"]
                sc = scores["summary_completeness"]["score"]
                sa = scores["summary_accuracy"]["score"]
                tc = scores["task_completeness"]["score"]
                ta = scores["task_assignment_accuracy"]["score"]
                tq = scores["task_quote_accuracy"]["score"]
                
                summary_score = (sc + sa) / 10.0
                task_score = (tc + ta + tq) / 15.0
                
                s_comp_scores.append(sc)
                s_acc_scores.append(sa)
                t_comp_scores.append(tc)
                t_assign_scores.append(ta)
                t_quote_scores.append(tq)
                
                f.write(f"| {name} | {duration_str} | {rtf_str} | {wer_str} | **{summary_score:.2f}** | {sc:.1f}/5 / {sa:.1f}/5 | **{task_score:.2f}** | {tc:.1f}/5 / {ta:.1f}/5 / {tq:.1f}/5 | ✅ Thành công |\n")
        
        f.write("\n")
        
        # Section 2: Averaged KPIs
        f.write("## 2. Các Chỉ Số KPI Đạt Được (Averaged KPIs)\n\n")
        
        avg_rtf = (total_transcribe_time / total_duration) if total_duration > 0 else 0
        avg_wer = (wer_sum / wer_count * 100) if wer_count > 0 else None
        
        f.write(f"- **Tỷ lệ thành công (Success Rate):** {successful_runs}/{len(results)} ({successful_runs/len(results)*100:.1f}%)\n")
        f.write(f"- **Hệ số thời gian thực trung bình (Avg RTF):** {avg_rtf:.3f} (Ví dụ: Audio 10 phút mất {10*avg_rtf:.1f} phút để dịch)\n")
        if avg_wer is not None:
            f.write(f"- **Tỷ lệ lỗi từ trung bình (Avg WER):** {avg_wer:.2f}%\n")
            
        if successful_runs > 0:
            avg_sc = sum(s_comp_scores) / len(s_comp_scores)
            avg_sa = sum(s_acc_scores) / len(s_acc_scores)
            avg_tc = sum(t_comp_scores) / len(t_comp_scores)
            avg_ta = sum(t_assign_scores) / len(t_assign_scores)
            avg_tq = sum(t_quote_scores) / len(t_quote_scores)
            
            avg_summary_score = (avg_sc + avg_sa) / 10.0
            avg_task_score = (avg_tc + avg_ta + avg_tq) / 15.0
            
            f.write(f"- **Đánh giá chất lượng Tóm tắt (Summary Quality):**\n")
            f.write(f"  - **Điểm Tóm tắt Tổng hợp (Avg Summary Score): {avg_summary_score:.2f} / 1.00**\n")
            f.write(f"  - Độ đầy đủ (Completeness): {avg_sc:.2f} / 5.0\n")
            f.write(f"  - Độ chính xác thông tin (Factual Accuracy): {avg_sa:.2f} / 5.0\n")
            f.write(f"- **Đánh giá chất lượng Giao việc (Task Assignment Quality):**\n")
            f.write(f"  - **Điểm Giao việc Tổng hợp (Avg Task Score): {avg_task_score:.2f} / 1.00**\n")
            f.write(f"  - Độ đầy đủ của task (Task Completeness): {avg_tc:.2f} / 5.0\n")
            f.write(f"  - Độ chính xác phân vai (Task Assignment Accuracy): {avg_ta:.2f} / 5.0\n")
            f.write(f"  - Độ chính xác trích dẫn (Task Quote Accuracy): {avg_tq:.2f} / 5.0\n\n")
        
        # Section 3: Detailed Feedback per test case
        f.write("## 3. Chi Tiết Đánh Giá Từng Mẫu Thử (Detailed Evaluation)\n\n")
        
        for r in results:
            if r["error"]:
                continue
            name = r["name"]
            scores = r["judge_scores"]
            
            sc = scores["summary_completeness"]["score"]
            sa = scores["summary_accuracy"]["score"]
            tc = scores["task_completeness"]["score"]
            ta = scores["task_assignment_accuracy"]["score"]
            tq = scores["task_quote_accuracy"]["score"]
            
            summary_score = (sc + sa) / 10.0
            task_score = (tc + ta + tq) / 15.0
            
            f.write(f"### Mẫu: {name}\n")
            f.write(f"- **Thời lượng:** {r['duration']/60:.2f} phút | **Thời gian chạy ASR:** {r['transcribe_time']:.1f}s | **Thời gian phân tích:** {r['analyze_time']:.1f}s\n")
            if r["wer"] is not None:
                f.write(f"- **Tỷ lệ lỗi từ (WER):** {r['wer']*100:.2f}%\n")
            f.write("- **Chi tiết chấm điểm từ LLM Trọng Tài (Gemini 2.5):**\n\n")
            
            f.write(f"  * **Tóm tắt - Độ đầy đủ (Summary Completeness) - {sc}/5:**\n")
            f.write(f"    > {scores['summary_completeness']['explanation']}\n\n")
            
            f.write(f"  * **Tóm tắt - Độ chính xác (Summary Accuracy) - {sa}/5:**\n")
            f.write(f"    > {scores['summary_accuracy']['explanation']}\n\n")
            
            f.write(f"  * 📊 **Điểm Tóm tắt Tổng hợp (Summary Score): {summary_score:.2f} / 1.00**\n\n")
            
            f.write(f"  * **Giao việc - Độ đầy đủ (Task Completeness) - {tc}/5:**\n")
            f.write(f"    > {scores['task_completeness']['explanation']}\n\n")
            
            f.write(f"  * **Giao việc - Đúng vai (Task Assignment Accuracy) - {ta}/5:**\n")
            f.write(f"    > {scores['task_assignment_accuracy']['explanation']}\n\n")
            
            f.write(f"  * **Giao việc - Khớp trích dẫn (Task Quote Accuracy) - {tq}/5:**\n")
            f.write(f"    > {scores['task_quote_accuracy']['explanation']}\n\n")
            
            f.write(f"  * 📊 **Điểm Giao việc Tổng hợp (Task Score): {task_score:.2f} / 1.00**\n\n")
            
            f.write(f"  * **Nhận xét chung:**\n")
            f.write(f"    > {scores['overall_comments']}\n\n")
            f.write("---\n\n")

